dofile('tests/combat/core_touch.lua')
local I=require('ui.TouchInput')
local T=require('ui.TouchControls')
local state={combat=false}
T.Attach({AddChild=function()end},function()return state end,nil,function()end)
if not I.IsEnabled() then I.Toggle() end;T.Sync()
T.BeginTouch(101,100,290);T.MoveTouch(101,100,250)
assert(I.Down('runIntent') and not I.KeyDown(KEY_SHIFT))
T.BeginTouch(102,532,338)
local out={};I.SampleRun(out,false);assert(out.runIntent and out.sprintIntent,'run button is the touch sprint')
T.MoveTouch(102,600,260);I.SampleRun(out,false);assert(out.runIntent and out.sprintIntent)
I.SetGamepadRun(true);T.EndTouch(102);T.EndTouch(101)
I.SampleRun(out,false);assert(out.runIntent and out.sprintIntent)
I.SetGamepadRun(false);I.SampleRun(out,true);assert(out.runIntent and out.sprintIntent)
I.SampleRun(out,false,true);assert(not out.runIntent and not out.sprintIntent,'walk toggle drops to a walk')
I.SampleRun(out,false);assert(out.runIntent and not out.sprintIntent,'default is a plain run, no sprint')
I.SampleRun(out,true,true);assert(out.runIntent and out.sprintIntent,'sprint key overrides walk mode')
state.combat=true;T.Sync();T.BeginTouch(103,676,338)
I.SampleRun(out,false,true);assert(out.runIntent and out.sprintIntent)
local revision=out.inputRevision;T.Cancel();I.SampleRun(out,false,true)
assert(out.inputRevision>revision and not out.runIntent and not out.sprintIntent)
state.combat=false;state.mounted=true;state.airborne=true;T.Sync()
T.BeginTouch(104,700,246);assert(I.Down('dash') and I.KeyDown(KEY_SHIFT))
I.SampleRun(out,false,true);assert(not out.runIntent and not out.sprintIntent,'dragon action remains independent')
T.Stop()
print('PASS held mobile/keyboard/gamepad run and capture/cancellation; dragon independent')
