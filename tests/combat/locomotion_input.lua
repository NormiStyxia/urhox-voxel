-- Reuse the established real TouchControls ownership fixture, then attach R9 modes.
dofile('tests/combat/core_touch.lua')
local I=require('ui.TouchInput')
local T=require('ui.TouchControls')
local state={combat=false}
local cancels=0
T.Attach({AddChild=function()end},function()return state end,nil,function()cancels=cancels+1 end)
if not I.IsEnabled() then I.Toggle() end;T.Sync()
T.BeginTouch(101,100,290);T.MoveTouch(101,100,250)
assert(I.Down('runIntent') and not I.KeyDown(KEY_SHIFT),'outer stick is not Shift or dash')
T.BeginTouch(102,532,338)
local out={};I.SampleEvade(out,false,false)
assert(out.evadePressed and out.evadeHeld,'exploration 64dp button starts on down')
T.MoveTouch(102,600,260);I.SampleEvade(out,false,false)
assert(not out.evadePressed and out.evadeHeld,'drag outside remains captured')
I.SetGamepadEvade(true);I.SampleEvade(out,true,true)
assert(out.evadePressed and out.evadeHeld)
T.EndTouch(102);I.SampleEvade(out,false,true);assert(out.evadeHeld,'touch release does not release keyboard')
I.SampleEvade(out,false,false);assert(out.evadeHeld,'keyboard release does not release pad')
I.SetGamepadEvade(false);I.SampleEvade(out,false,false);assert(not out.evadeHeld and not out.evadePressed)
-- Read ALL edges even when one source wins; no leftover event on the next frame.
I.Set('evadeRun',true);I.Set('evadeRun',false);I.Set('dodge',true);I.Set('dodge',false)
I.SampleEvade(out,true,false);assert(out.evadePressed and not out.evadeHeld)
I.SampleEvade(out,false,false);assert(not out.evadePressed)
state.combat=true;T.Sync();assert(I.MoveAxis()>0 and not I.Down('runIntent'))
T.BeginTouch(103,676,338);I.SampleEvade(out,false,false);assert(out.evadePressed and out.evadeHeld)
local revision=out.inputRevision
T.Cancel();I.SampleEvade(out,false,false)
assert(out.inputRevision>revision and not out.evadeHeld and not out.evadePressed and cancels>0)
state.combat=false;state.mounted=true;state.airborne=true;T.Sync()
T.BeginTouch(104,700,246);assert(I.Down('dash') and I.KeyDown(KEY_SHIFT))
I.SampleEvade(out,false,false);assert(not out.evadePressed and not out.evadeHeld,'dragon button is never foot dodge')
T.Stop()
print('PASS R9 actual mobile button/capture/cancel, outer-ring runIntent, source edge merge/release, independent dragon dash')
