"""clock_catalyst_game.json (clock_catalyst_v6_blender.py, CLOCK_EXPORT=1) -> scripts/combat/models/ClockCatalyst.lua
Vertex = 8 ints: pos x,y,z (1e-4 m), normal x,y,z (1e-3), kind, a (x100).
kind: 0 star-metal band, 1 silver, 2 gold sparkle, 3 numeral, 4 glass blade, 5 sapphire (a = facet), 6 ice shard.
Game axes: X right, Y up, -Z = the front face (camera behind the caster sees it). Parts rotate about their own pivots.
usage: python3 art/weapon_gen/clock_catalyst_export.py in.json out.lua"""
import json, sys
import numpy as np
d = json.load(open(sys.argv[1]))

def orient(rows):
    out, flipped = [], 0
    for i in range(0, len(rows), 3):
        a, b, c = rows[i:i + 3]
        pa, pb, pc = np.array(a[:3]), np.array(b[:3]), np.array(c[:3])
        n = np.array(a[3:6])
        if np.dot(np.cross(pb - pa, pc - pa), n) < 0:
            b, c = c, b
            flipped += 1
        out += [a, b, c]
    return out, flipped

def pack(rows):
    rows, fl = orient(rows)
    table, verts, idx = {}, [], []
    for r in rows:
        key = (round(r[0] * 1e4), round(r[1] * 1e4), round(r[2] * 1e4), round(r[3] * 1e3), round(r[4] * 1e3),
               round(r[5] * 1e3), int(r[6]), round(r[7] * 100))
        if key not in table:
            table[key] = len(verts) + 1
            verts.append(key)
        idx.append(table[key])
    return verts, idx, fl

def fmt(values, per):
    return '\n'.join('    ' + ','.join(str(v) for v in values[i:i + per]) + ',' for i in range(0, len(values), per))

allv = np.array([r for k in d for r in d[k]])
mn, mx = allv[:, :3].min(0), allv[:, :3].max(0)
out = ['-- GENERATED by art/weapon_gen/clock_catalyst_export.py (from clock_catalyst_v6_blender.py) - do not hand edit.',
       '-- Time catalyst, game LOD. Metres, origin = orb centre, +Y up, -Z = front face (camera behind the caster).',
       '-- Vertex = 8 ints: pos x,y,z (1e-4 m), normal x,y,z (1e-3), kind, a (x100).',
       '--   kind 0 star-metal band, 1 silver, 2 gold sparkle, 3 numeral, 4 glass blade, 5 sapphire (a = facet brightness), 6 ice shard.',
       'return {', '  name="clock_catalyst", scale=10000, nscale=1000,',
       '  bounds={min={%.4f,%.4f,%.4f},max={%.4f,%.4f,%.4f}},' % (*mn, *mx),
       '  radius=%.4f, coreRadius=0.088,' % float(np.abs(allv[:, :3]).max())]
total = 0
for name in ('bands', 'blades', 'gems', 'shards', 'core'):
    verts, idx, fl = pack(d[name])
    total += len(idx) // 3
    out.append('  %s={triangles=%d,' % (name, len(idx) // 3))
    out.append('   v={\n' + fmt([n for v in verts for n in v], 8) + '\n   },')
    out.append('   i={\n' + fmt(idx, 15) + '\n   }},')
out.append('}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('wrote', sys.argv[2], 'triangles', total)
