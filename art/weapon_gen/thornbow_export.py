"""thornbow_game.json (from thornbow_blender.py export) -> scripts/combat/models/ThornBow.lua.
Indexed vertices, 11 ints each: pos x,y,z (1e-4 m), normal x,y,z (1e-3), r,g,b weights (x100),
alpha param (x100: petal u / grip strap), glow (x100: 0 body, .35 crystal core, 1 emissive).
usage: python3 art/weapon_gen/thornbow_export.py art/weapon_gen/out/thornbow_game.json scripts/combat/models/ThornBow.lua"""
import json, sys
import numpy as np
d = json.load(open(sys.argv[1]))
allv = np.array(d['parts']['body'] + d['parts']['string'])
mn, mx = allv[:, :3].min(0), allv[:, :3].max(0)
sv = np.array(d['parts']['string'])

def orient(rows):
    # The Blender->game axis map is a reflection: re-wind every triangle so (b-a)x(c-a) agrees with its normals
    # (same convention as ForgeShowroomBlades.Face: standard cross product points outward).
    out, flipped = [], 0
    for i in range(0, len(rows), 3):
        a, b, c = rows[i:i + 3]
        pa, pb, pc = np.array(a[:3]), np.array(b[:3]), np.array(c[:3])
        n = np.array(a[3:6]) + np.array(b[3:6]) + np.array(c[3:6])
        if np.dot(np.cross(pb - pa, pc - pa), n) < 0:
            b, c = c, b
            flipped += 1
        out += [a, b, c]
    print('flipped', flipped, 'of', len(rows) // 3)
    return out

def pack(rows):
    table, verts, idx = {}, [], []
    for r in orient(rows):
        key = (round(r[0] * 1e4), round(r[1] * 1e4), round(r[2] * 1e4),
               round(r[3] * 1e3), round(r[4] * 1e3), round(r[5] * 1e3),
               round(r[6] * 100), round(r[7] * 100), round(r[8] * 100), round(r[9] * 100), round(r[10] * 100))
        if key not in table:
            table[key] = len(verts) + 1
            verts.append(key)
        idx.append(table[key])
    return verts, idx

def fmt(values, per_line):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append('    ' + ','.join(str(v) for v in values[i:i + per_line]) + ',')
    return '\n'.join(lines)

out = ['-- GENERATED by art/weapon_gen/thornbow_export.py (from thornbow_blender.py export) - do not hand edit.',
       '-- Thorn-flower bow, game LOD. Metres, origin = grip centre, +Y up (limbs), +Z target, string on -Z.',
       '-- Vertex = 11 ints: pos x,y,z (1e-4 m), normal x,y,z (1e-3), r,g,b (x100), alpha param (x100), glow (x100).',
       '--   r wood, g petal (glow 1 = flower heart), b crystal (glow .35 core, glow 1 = bow string), 0,0,0 = cloth grip.',
       '--   alpha param: petal u (0 base .. 1 tip) / grip strap phase; 1 elsewhere. Indices are 1-based triples.',
       'return {', '  name="thorn_bow", scale=10000, nscale=1000,',
       '  height=%.4f,' % (mx[1] - mn[1]),
       '  bounds={min={%.4f,%.4f,%.4f},max={%.4f,%.4f,%.4f}},' % (*mn, *mx),
       '  sockets={grip={0,0,0},top={0,%.4f,0},bottom={0,%.4f,0},stringZ=%.4f,crystalTip=%.4f},' % (mx[1], mn[1], sv[:, 2].mean(), allv[(allv[:, 8] == 1) & (allv[:, 10] < 0.9)][:, 2].max())]
for part in ('body', 'string'):
    verts, idx = pack(d['parts'][part])
    out.append('  %s={triangles=%d,' % (part, len(idx) // 3))
    out.append('   v={\n' + fmt([n for v in verts for n in v], 11) + '\n   },')
    out.append('   i={\n' + fmt(idx, 15) + '\n   }},')
out.append('}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('wrote', sys.argv[2], 'body tris', len(d['parts']['body']) // 3)
