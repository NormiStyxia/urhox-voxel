local Brush = require("ruins.VoxelBrush")
function Start()
    local scene = Scene()
    scene:CreateComponent("Octree")
    local world = scene:CreateComponent("VoxelPhysicsWorld")
    local b = Brush.New(world, { min = { -2, 0, -2 }, max = { 2, 2, 2 }, size = 0.25 })
    print("dims " .. b.nx .. " " .. b.ny .. " " .. b.nz)
    local i0, i1 = b:Range(-1, 1, 1)
    print("range " .. tostring(i0) .. " " .. tostring(i1) .. " " .. math.type(i0))
    b:Shape(-1, 0, -1, 1, 1, 1, function() return 100 end)
    print("solid after shape " .. b.volume:GetSolidCount() .. " grid " .. b.grid:GetSolidCount())
    b:Box(-2, 1.5, -2, 2, 2, 2, 101)
    print("solid after box " .. b.volume:GetSolidCount() .. " grid " .. b.grid:GetSolidCount())
    local v = b:Finish({})
    print("finish " .. tostring(v) .. " pos " .. tostring(v and v:GetNode().worldPosition))
end
